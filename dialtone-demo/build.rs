//! Class names for the playground Class tab.
//!
//! Reads the vendored Dialtone stylesheets and the component docs, then writes
//! `class_catalog.rs` into `OUT_DIR`. The demo includes that file so the wasm
//! bundle does not parse the stylesheets in the browser.

use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let css_files = [
        manifest.join("../dialtone/assets/css/dialtone.css"),
        manifest.join("../dialtone/assets/css/illustrations.css"),
    ];
    let content_dir = manifest.join("src/docs/content");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", content_dir.display());
    for path in &css_files {
        println!("cargo:rerun-if-changed={}", path.display());
    }

    let mut classes = BTreeSet::new();
    for path in &css_files {
        let css = fs::read_to_string(path)
            .unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
        collect_classes(&css, &mut classes);
    }
    if classes.len() < 1000 {
        panic!(
            "expected Dialtone class names in the stylesheets, found {}",
            classes.len()
        );
    }

    let mut docs: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let entries = fs::read_dir(&content_dir)
        .unwrap_or_else(|error| panic!("read {}: {error}", content_dir.display()));
    for entry in entries {
        let entry = entry.expect("docs content entry");
        let path = entry.path();
        if path.extension().and_then(|ext| ext.to_str()) != Some("md") {
            continue;
        }
        println!("cargo:rerun-if-changed={}", path.display());
        let stem = path
            .file_stem()
            .and_then(|stem| stem.to_str())
            .unwrap_or_default()
            .to_string();
        let text = fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
        let mut found = BTreeSet::new();
        collect_classes(&text, &mut found);
        found.retain(|class| classes.contains(class));
        let page_ids: &[&str] = if stem == "tabs" {
            &["tab", "tab-group"]
        } else {
            &[]
        };
        if page_ids.is_empty() {
            docs.entry(stem).or_default().extend(found);
        } else {
            for id in page_ids {
                docs.entry((*id).to_string())
                    .or_default()
                    .extend(found.iter().cloned());
            }
        }
    }

    let mut rust = String::from("// Generated by dialtone-demo/build.rs. Do not edit.\n");
    rust.push_str("static CSS_CLASSES: &[&str] = &[\n");
    for class in &classes {
        rust.push_str("    \"");
        rust.push_str(class);
        rust.push_str("\",\n");
    }
    rust.push_str("];\n\n");

    let mut arms = Vec::new();
    for (id, names) in &docs {
        if names.is_empty() {
            continue;
        }
        let static_name = static_name(id);
        rust.push_str("static ");
        rust.push_str(&static_name);
        rust.push_str(": &[&str] = &[\n");
        for class in names {
            rust.push_str("    \"");
            rust.push_str(class);
            rust.push_str("\",\n");
        }
        rust.push_str("];\n\n");
        arms.push((id.clone(), static_name));
    }

    rust.push_str("fn doc_classes(id: &str) -> &'static [&'static str] {\n    match id {\n");
    for (id, static_name) in &arms {
        rust.push_str("        \"");
        rust.push_str(id);
        rust.push_str("\" => ");
        rust.push_str(static_name);
        rust.push_str(",\n");
    }
    rust.push_str("        _ => &[],\n    }\n}\n");

    fs::write(out_dir.join("class_catalog.rs"), rust).expect("write class catalog");
}

fn static_name(id: &str) -> String {
    let mut name = String::from("DOC_");
    for ch in id.chars() {
        if ch.is_ascii_alphanumeric() {
            name.push(ch.to_ascii_uppercase());
        } else {
            name.push('_');
        }
    }
    name
}

/// Class tokens whose names start with `d-`, `base-`, or `dt-`.
fn collect_classes(source: &str, out: &mut BTreeSet<String>) {
    let bytes = source.as_bytes();
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index] == b'/' && bytes.get(index + 1) == Some(&b'*') {
            index += 2;
            while index + 1 < bytes.len() && !(bytes[index] == b'*' && bytes[index + 1] == b'/') {
                index += 1;
            }
            index = (index + 2).min(bytes.len());
            continue;
        }
        if bytes[index].is_ascii_alphabetic() && (index == 0 || !is_class_char(bytes[index - 1])) {
            let start = index;
            index += 1;
            while index < bytes.len() && is_class_char(bytes[index]) {
                index += 1;
            }
            let token = &source[start..index];
            if is_dialtone_class(token) {
                out.insert(token.to_string());
            }
            continue;
        }
        index += 1;
    }
}

fn is_class_char(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || byte == b'_' || byte == b'-'
}

fn is_dialtone_class(token: &str) -> bool {
    token.starts_with("d-") || token.starts_with("base-") || token.starts_with("dt-")
}
